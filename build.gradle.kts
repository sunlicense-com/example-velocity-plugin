plugins {
    java
    // Puts the SunLicense SDK inside the plugin jar under your own package (see shadowJar below).
    id("com.gradleup.shadow") version "9.6.1"
    // ./gradlew runVelocity starts a local Velocity proxy with the plugin installed.
    id("xyz.jpenilla.run-velocity") version "3.1.0"
}

repositories {
    mavenCentral()
    maven("https://repo.papermc.io/repository/maven-public/")
}

dependencies {
    // Built against Velocity 3.5 (Java 21): the jar runs on Velocity 3.5 and on 4.x.
    compileOnly("com.velocitypowered:velocity-api:3.5.1")
    annotationProcessor("com.velocitypowered:velocity-api:3.5.1")   // writes velocity-plugin.json from @Plugin
    // The official SunLicense Java SDK (MIT, no dependencies): https://github.com/sunlicense-com/sunlicense-java
    implementation("com.sunlicense:sunlicense:0.0.1")

    testImplementation(platform("org.junit:junit-bom:5.13.4"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
    // Velocity ships Gson at runtime; the tests need their own copy.
    testImplementation("com.google.code.gson:gson:2.13.2")
}

java {
    toolchain.languageVersion = JavaLanguageVersion.of(21)
}

// @Plugin needs the version as a constant: BuildInfo.VERSION, generated from gradle.properties.
val generateBuildInfo by tasks.registering {
    val dir = layout.buildDirectory.dir("generated/sources/buildinfo")
    val version = project.version.toString()
    inputs.property("version", version)
    outputs.dir(dir)
    doLast {
        val file = dir.get().file("com/example/myplugin/BuildInfo.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package com.example.myplugin;\n\n/** Generated by build.gradle.kts. */\nfinal class BuildInfo {\n" +
                "    static final String VERSION = \"$version\";\n\n    private BuildInfo() {\n    }\n}\n"
        )
    }
}
sourceSets.main { java.srcDir(generateBuildInfo) }

tasks {
    processResources {
        // SunLicense settings from gradle.properties, -P flags or ORG_GRADLE_PROJECT_* environment variables.
        val values = mapOf(
            "sunlicenseUrl" to (project.findProperty("sunlicenseUrl") ?: "https://api.sunlicense.com").toString(),
            "sunlicenseApiKey" to (project.findProperty("sunlicenseApiKey") ?: "").toString(),
            "sunlicensePublicKey" to (project.findProperty("sunlicensePublicKey") ?: "").toString(),
        )
        inputs.properties(values)
        filesMatching("sunlicense.properties") {
            expand(values)
        }
    }

    shadowJar {
        archiveClassifier = ""
        // Relocate the SDK so two plugins with different SDK versions never clash on one proxy.
        relocate("com.sunlicense", "${project.group}.myplugin.libs.sunlicense")
    }

    jar {
        archiveClassifier = "plain"
    }

    build {
        dependsOn(shadowJar)
    }

    test {
        useJUnitPlatform()
    }

    runVelocity {
        velocityVersion("3.5.1")
    }
}
